const {test,expect}=require('@playwright/test');
const f=(page,k)=>page.locator('#sb-bookings-editor [data-bk="'+k+'"]');
const tx=(page,k)=>page.locator('#sb-bookings-editor [data-bk-tx="'+k+'"]');
test('manual BRL quote and BRL deposit use different exchange rates with evidence',async({page})=>{
 await page.goto('/',{waitUntil:'domcontentloaded'});
 await page.locator('[data-view="bookings"]').click();
 await page.locator('[data-bk-payment-details] summary').click();
 await f(page,'type').selectOption('transport');
 await f(page,'stageId').selectOption('1');
 await f(page,'status').selectOption('confirmed');
 await f(page,'title').fill('Brazilian bus');
 await f(page,'provider').fill('Test Operator');
 await f(page,'reference').fill('BUS-2027');
 await f(page,'currency').fill('BRL');
 await expect(f(page,'rateEUR')).toBeVisible();
 await f(page,'totalEUR').fill('500');
 await f(page,'rateEUR').fill('0.16');
 await f(page,'rateCheckedAt').fill('2026-10-13');
 await f(page,'rateSource').fill('Example quote checked manually');
 await tx(page,'date').fill('2026-10-13');
 await tx(page,'amount').fill('200');
 await tx(page,'currency').fill('BRL');
 await expect(tx(page,'rateEUR')).toBeVisible();
 await tx(page,'rateEUR').fill('0.15');
 await tx(page,'rateCheckedAt').fill('2026-10-13');
 await tx(page,'rateSource').fill('Card receipt');
 await page.locator('[data-bk-add-payment]').click();
 await expect(page.locator('[data-bk-payment-list]')).toContainText('200 BRL');
 page.once('dialog',d=>d.accept());
 await page.locator('[data-bk-save]').click();
 const result=await page.evaluate(()=>{
  const m=JSON.parse(localStorage.getItem('southbound-v3'));
  const p=window.SouthboundItinerary.plan({stops:STOPS,start:m.tripStart,excluded:m.excluded,days:m.days,order:m.routeOrder});
  const r=window.SouthboundBookingLedger.reconcile({items:p.items,bookings:m.bookingLedger});
  return {b:m.bookingLedger[0],cost:r.items[1].leg,alloc:r.typedPaidByStop[1],spent:r.extraPaid};
 });
 expect(result.b.currency).toBe('BRL');
 expect(result.b.totalAmount).toBe(500);
 expect(result.b.totalEUR).toBe(80);
 expect(result.b.transactions).toHaveLength(1);
 expect(result.b.paidEUR).toBe(30);
 expect(result.cost).toBe(80);
 expect(result.alloc.transfer).toBe(30);
 expect(result.spent).toBe(30);
});
test('adding a dated EUR payment retains prior aggregate payments',async({page})=>{
 await page.goto('/',{waitUntil:'domcontentloaded'});
 await expect.poll(()=>page.evaluate(()=>!!localStorage.getItem('southbound-v3'))).toBe(true);
 await page.evaluate(()=>{
  const m=JSON.parse(localStorage.getItem('southbound-v3'));
  m.bookingLedger=[{id:'legacy-1',type:'transport',stageId:1,fromStageId:0,status:'planned',title:'Earlier booking',provider:'Operator',startDate:'2026-12-31',endDate:'',totalEUR:90,paidEUR:25,refundedEUR:5,recordedElsewhere:false,reference:''}];
  localStorage.setItem('southbound-v3',JSON.stringify(m));
 });
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('[data-view="bookings"]').click();
 await page.locator('[data-bk-edit]').first().click();
 await page.locator('[data-bk-payment-details] summary').click();
 await expect(f(page,'paidEUR')).toHaveValue('25');
 await tx(page,'date').fill('2026-10-13');
 await tx(page,'currency').fill('EUR');
 await tx(page,'amount').fill('10');
 await page.locator('[data-bk-add-payment]').click();
 await expect(f(page,'paidEUR')).toBeDisabled();
 await page.locator('[data-bk-save]').click();
 const record=await page.evaluate(()=>JSON.parse(localStorage.getItem('southbound-v3')).bookingLedger[0]);
 expect(record.legacyPaidEUR).toBe(25);expect(record.legacyRefundedEUR).toBe(5);
 expect(record.paidEUR).toBe(35);expect(record.refundedEUR).toBe(5);
 expect(record.transactions).toHaveLength(1);
 await page.locator('[data-bk-edit]').first().click();
 await expect(page.locator('[data-bk-payment-list]')).toContainText('10 EUR');
});
